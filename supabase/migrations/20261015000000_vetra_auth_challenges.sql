-- ── auth_challenges ──────────────────────────────────────────────────────────
-- Stores short-lived, single-use nonces issued by auth-challenge Edge Function.
-- Only the service role (Edge Functions) can read or write this table.
-- consumed_at is set atomically by auth-verify on first use.
-- Rows older than 1 hour can be purged by a scheduled job (see SUPABASE-SETUP.md).

CREATE TABLE auth_challenges (
    nonce        UUID PRIMARY KEY,                              -- generated by auth-challenge
    address      TEXT NOT NULL,                                 -- G… Stellar address
    expires_at   TIMESTAMPTZ NOT NULL,
    consumed_at  TIMESTAMPTZ,                                   -- NULL = unused, non-NULL = consumed
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_auth_challenges_address ON auth_challenges(address);
CREATE INDEX idx_auth_challenges_expires ON auth_challenges(expires_at);

-- No user-facing RLS policies — service_role only.
-- This table must NOT be readable by anon or authenticated roles.
ALTER TABLE auth_challenges ENABLE ROW LEVEL SECURITY;
-- (no POLICY created → table is inaccessible to all non-service_role users)

-- ── Fix SECURITY DEFINER search_path ─────────────────────────────────────────
-- Without SET search_path, a SECURITY DEFINER function running as the database
-- owner could be tricked into calling objects from an attacker-controlled schema.
-- Explicitly setting search_path to `public, pg_temp` closes this vector.

CREATE OR REPLACE FUNCTION is_guardian_of(p_pet_id UUID)
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM pet_guardians pg
        JOIN profiles pr ON pg.profile_id = pr.id
        WHERE pg.pet_id = p_pet_id
          AND pr.auth_user_id = auth.uid()
    );
$$;

CREATE OR REPLACE FUNCTION register_pet(
    p_profile_id           UUID,
    p_vet_id               TEXT,
    p_name                 TEXT,
    p_species              TEXT,
    p_breed                TEXT,
    p_sex                  TEXT,
    p_birth_date           DATE,
    p_birth_date_estimated BOOLEAN,
    p_color                TEXT,
    p_microchip            TEXT
) RETURNS pets LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_pet     pets;
    v_profile profiles;
BEGIN
    -- Verify the caller owns this profile.
    SELECT * INTO v_profile
    FROM profiles
    WHERE id = p_profile_id AND auth_user_id = auth.uid();
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Unauthorized: profile does not belong to current user';
    END IF;

    -- Belt-and-suspenders vet_id uniqueness check (UNIQUE constraint also enforces this).
    IF EXISTS (SELECT 1 FROM pets WHERE vet_id = p_vet_id) THEN
        RAISE EXCEPTION 'DuplicateVetId: % already registered', p_vet_id;
    END IF;

    INSERT INTO pets (vet_id, name, species, breed, sex, birth_date,
                      birth_date_estimated, color, microchip)
    VALUES (p_vet_id, p_name, p_species, p_breed, p_sex, p_birth_date,
            p_birth_date_estimated, p_color, p_microchip)
    RETURNING * INTO v_pet;

    INSERT INTO pet_guardians (pet_id, profile_id, relationship, is_primary)
    VALUES (v_pet.id, p_profile_id, 'owner', TRUE);

    INSERT INTO stellar_identities (pet_id, status)
    VALUES (v_pet.id, 'local');

    INSERT INTO public_passports (pet_id, is_public)
    VALUES (v_pet.id, TRUE);

    RETURN v_pet;
END;
$$;
